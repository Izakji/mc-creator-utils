package com.izakji.mccreatorutils.locate.engine;

/**
 * The five height-independent climate axes used by biome placement.
 *
 * @author Izakji
 */
public enum ClimateAxis {
    /** Temperature parameter. */
    TEMPERATURE,
    /** Humidity parameter. */
    HUMIDITY,
    /** Continentalness parameter. */
    CONTINENTALNESS,
    /** Erosion parameter. */
    EROSION,
    /** Weirdness parameter. */
    WEIRDNESS
}
